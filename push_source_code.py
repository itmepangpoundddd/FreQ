#!/usr/bin/env python3
"""Commit and push FreQ source code to GitHub — root-level files only.

Upload policy (SP1):
  * EVERY file in the repository root is pushed, regardless of extension —
    the old whitelist silently dropped files from GitHub.
  * NEVER uploaded, and actively REMOVED from the index when already
    tracked (so they disappear from GitHub on the next push):
      - anything inside a folder (templates/, deps/, …)
      - *.bat build scripts
      - release.py
      - push_source_code.py (this script)
  * Files matched by .gitignore are force-added, matching the previous
    behaviour for runtime payloads (.pyd/.lib) the repo ships ready-to-run.
"""

from __future__ import annotations

import argparse
import re
import subprocess
import sys
import time
from pathlib import Path

# Keep em-dashes in help text intact on a non-UTF-8 console.
if hasattr(sys.stdout, "reconfigure"):
    sys.stdout.reconfigure(encoding="utf-8", errors="replace")
    sys.stderr.reconfigure(encoding="utf-8", errors="replace")


ROOT = Path(__file__).resolve().parent

# Never uploaded — and untracked from the index when already on GitHub.
ALWAYS_EXCLUDE = {"release.py", "push_source_code.py"}
# Build junk: object files and their linker export twins.
EXCLUDED_SUFFIXES = {".bat", ".obj", ".exp"}
# Generated at build time or local application data — kept out even though
# they are root-level files (mirrors the old GENERATED_EXCLUDES intent and
# the entries .gitignore already guards).
GENERATED_EXCLUDES = {
    "version.txt",       # stamped from installer.iss on every build
    "FreQ.spec",         # generated by PyInstaller
    "radio_queue.json",  # live station data
    "radio_queue.freq",  # live station data
}


def _excluded(rel_path: str) -> bool:
    """True when ``rel_path`` must never live on GitHub."""
    # Anything inside a folder is out of scope entirely.
    if "/" in rel_path or "\\" in rel_path:
        return True
    path = Path(rel_path)
    if path.name in ALWAYS_EXCLUDE or path.name in GENERATED_EXCLUDES:
        return True
    if path.suffix.lower() in EXCLUDED_SUFFIXES:
        return True
    return False


def run(*args: str, capture: bool = False) -> str:
    result = subprocess.run(
        args,
        cwd=ROOT,
        check=True,
        text=True,
        capture_output=capture,
    )
    return result.stdout.strip() if capture else ""


def version() -> str:
    installer = ROOT / "installer.iss"
    match = re.search(
        r'^\s*#define\s+MyAppVersion\s+"([^"]+)"',
        installer.read_text(encoding="utf-8"),
        re.MULTILINE,
    )
    return match.group(1) if match else "unknown"


def is_ignored(path: str) -> bool:
    return subprocess.run(
        ["git", "check-ignore", "-q", "--", path],
        cwd=ROOT,
        check=False,
    ).returncode == 0


def untrack_forbidden() -> list[str]:
    """Remove tracked-but-forbidden paths from the index (files stay on disk).

    The old whitelist script force-added *.bat and pushed templates/, so
    those already sit on GitHub — dropping them from the staging list alone
    would leave them there forever. Returns the removed paths for reporting.
    """
    tracked = run("git", "ls-files", capture=True).splitlines()
    victims = sorted(p for p in tracked if _excluded(p))
    if victims:
        run("git", "rm", "-q", "--cached", "--", *victims)
    return victims


def stage_source() -> None:
    # Stage every remaining root-level file, any extension.
    names = sorted(
        path.name
        for path in ROOT.iterdir()
        if path.is_file() and not _excluded(path.name)
    )
    # .gitignore blocks runtime payloads (.pyd/.lib) shipped ready-to-run —
    # force-add them because the policy says everything in root goes up.
    forced = sorted(name for name in names if is_ignored(name))
    plain = sorted(set(names) - set(forced))
    if plain:
        run("git", "add", "--", *plain)
    if forced:
        run("git", "add", "-f", "--", *forced)
    # "Push everything" includes deletions: a tracked root file removed
    # from disk must leave GitHub too (e.g. deleted screenshots).
    gone = [
        path
        for path in run("git", "ls-files", capture=True).splitlines()
        if "/" not in path and not (ROOT / path).exists()
    ]
    if gone:
        run("git", "add", "--", *gone)


def fresh_push(branch: str, message: str) -> str:
    """Replace the remote branch with a SINGLE clean snapshot commit.

    Everything that ever lived in the branch history (templates/, .bat
    files, release.py, old build junk) disappears from GitHub entirely —
    a normal "delete files in a new commit" leaves them recoverable in
    history forever. Steps:
      1. back the old history up as a LOCAL branch (never pushed)
      2. create an orphan commit from the already-curated index
      3. rename it over the working branch and force-push it
    Returns the local backup branch name.
    """
    backup = f"backup/{branch}-before-fresh-{time.strftime('%Y%m%d-%H%M%S')}"
    run("git", "branch", backup)                      # old history, local only
    run("git", "checkout", "--orphan", "__freq_fresh_push")
    run("git", "commit", "-m", message)
    run("git", "branch", "-M", branch)               # replace branch pointer
    run("git", "push", "--force", "origin", branch)
    return backup


def main() -> None:
    parser = argparse.ArgumentParser(
        description="Push FreQ source code to GitHub (root-files policy).",
        epilog=(
            "examples:\n"
            "  python push_source_code.py -m \"Update source\""
            "   commit + push tracked root files\n"
            "  python push_source_code.py --dry-run"
            "                show what would be pushed, change nothing\n"
            "  python push_source_code.py --fresh"
            "                 REWRITE remote history to one clean snapshot\n"
            "                                                 (old history stays on a local backup branch)\n"
        ),
        formatter_class=argparse.RawDescriptionHelpFormatter,
    )
    parser.add_argument("-m", "--message", help="commit message")
    parser.add_argument(
        "--fresh",
        action="store_true",
        help="replace the remote branch with ONE clean snapshot commit — "
             "the entire old history (templates/, .bat, release.py, build "
             "junk) disappears from GitHub; a local backup branch keeps it",
    )
    parser.add_argument("--dry-run", action="store_true", help="show staged changes without committing")
    args = parser.parse_args()

    branch = run("git", "branch", "--show-current", capture=True)
    if not branch:
        raise RuntimeError("The current checkout is not on a branch")
    remote = run("git", "remote", "get-url", "origin", capture=True)
    if not remote:
        raise RuntimeError("Git remote 'origin' is not configured")

    removed = untrack_forbidden()
    if removed:
        print(f"Untracked from GitHub (kept on disk): {len(removed)} file(s)")
        for path in removed:
            print(f"  - {path}")
    stage_source()

    staged = run("git", "diff", "--cached", "--name-status", capture=True)
    if not staged:
        print("No source changes to push.")
        return
    print(staged)
    if args.dry_run:
        print("Dry run: nothing was committed or pushed.")
        return

    message = args.message or f"Update source for FreQ v{version()}"
    if not args.fresh:
        run("git", "commit", "-m", message)
        run("git", "push", "origin", branch)
        print(f"Source pushed to {remote} ({branch}).")
        return

    backup = fresh_push(branch, message)
    print(f"\nFresh history pushed to {remote} ({branch}).")
    print(f"Old history backed up locally as '{backup}' (never pushed).")
    print("Delete it once satisfied: git branch -D " + backup)


if __name__ == "__main__":
    try:
        main()
    except (RuntimeError, subprocess.CalledProcessError) as error:
        print(f"ERROR: {error}", file=sys.stderr)
        raise SystemExit(1)
